#!/usr/bin/env bash
# ==============================================================================
# Aggregate the per-suite SDK reports produced by gen_sdk_report.sh.
#
# Two artefacts come out of this:
#
#   1. <report-dir>/summary.md — one table, suites x combinations, so the six
#      storage/topology combinations can be compared at a glance instead of by
#      opening six files.
#   2. sdk-tests/<suite>/TEST_REPORT.md — the same format the hand-written
#      nacos-java report used, now generated for every suite and refreshed on
#      each matrix run. This is the durable, in-repo artefact; the timestamped
#      report dir is the run-scoped one.
#
# Usage:
#   gen_sdk_summary.sh <results.tsv> <report-dir> <combo-order...>
#
# results.tsv lines: <combo>|<suite>|<total>|<passed>|<failed>|<errors>|<skipped>
# ==============================================================================

set -uo pipefail

RESULTS="${1:?usage: gen_sdk_summary.sh <results.tsv> <report-dir> [combo...]}"
DIR="${2:?}"
shift 2
COMBOS=("$@")

[ -f "$RESULTS" ] || { echo "no results file: $RESULTS" >&2; exit 1; }
mkdir -p "$DIR"

# <suite>|<display title>|<sdk-tests dir>
SUITES=(
    "nacos-java|Nacos Java SDK|nacos-java-tests"
    "apollo-java|Apollo Java SDK|apollo-java-tests"
    "consul-go|Consul Go SDK|consul-go-tests"
    "batata-client|batata-client SDK|batata-client-tests"
    "batata-consul-client|batata-consul-client SDK|batata-consul-client-tests"
    "batata-maintainer|batata-maintainer SDK|batata-maintainer-tests"
)

entry() { # <combo> <suite> -> the tsv line, or empty
    awk -F'|' -v c="$1" -v s="$2" '$1==c && $2==s {print; exit}' "$RESULTS"
}

cell() { # <combo> <suite> -> "passed/total"
    local line p t
    line=$(entry "$1" "$2")
    if [ -z "$line" ]; then echo "-"; return; fi
    p=$(cut -d'|' -f4 <<<"$line")
    t=$(cut -d'|' -f3 <<<"$line")
    if [ "$t" = "0" ]; then echo "-"; else
        if [ "$p" = "$t" ]; then echo "**${p}/${t}**"; else echo "${p}/${t}"; fi
    fi
}

# ---------------------------------------------------------------------------
# 1. Cross-combination summary
# ---------------------------------------------------------------------------
{
    echo "# Batata SDK Compatibility Matrix"
    echo
    echo "- **Generated:** $(date '+%Y-%m-%d %H:%M:%S %z')"
    echo "- **Combinations:** ${COMBOS[*]}"
    echo "- **Cell:** passed/total (bold = fully green)"
    echo
    echo "> Auto-generated by \`scripts/gen_sdk_summary.sh\`. Do not hand-edit."
    echo
    printf '| Suite |'
    for c in "${COMBOS[@]}"; do printf ' %s |' "$c"; done
    echo
    # `printf '------|'` is parsed as an option because of the leading dashes;
    # the format string has to be explicit.
    printf '|-------|'
    for c in "${COMBOS[@]}"; do printf '%s' '------|'; done
    echo
    for s in "${SUITES[@]}"; do
        IFS='|' read -r key title _dir <<<"$s"
        printf '| %s |' "$title"
        for c in "${COMBOS[@]}"; do printf ' %s |' "$(cell "$c" "$key")"; done
        echo
    done
    echo
    echo "## Raw counts"
    echo
    echo '```'
    echo "combo|suite|total|passed|failed|errors|skipped"
    sort "$RESULTS"
    echo '```'
} > "${DIR}/summary.md"

# ---------------------------------------------------------------------------
# 2. Per-suite TEST_REPORT.md in sdk-tests/
# ---------------------------------------------------------------------------
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

for s in "${SUITES[@]}"; do
    IFS='|' read -r key title reldir <<<"$s"
    out="${ROOT}/sdk-tests/${reldir}/TEST_REPORT.md"
    [ -d "${ROOT}/sdk-tests/${reldir}" ] || continue

    # Reference combination for the detailed part: prefer standalone-rock (the
    # cheapest deterministic run), else whatever was recorded first.
    ref=""
    for c in standalone-rock "${COMBOS[@]}"; do
        [ -n "$(entry "$c" "$key")" ] && { ref="$c"; break; }
    done
    if [ -z "$ref" ]; then
        echo "SKIP ${key}: no results" >&2
        continue
    fi
    ref_line=$(entry "$ref" "$key")
    IFS='|' read -r _ _ total passed failed errors skipped <<<"$ref_line"

    # The failure list lives in the per-combo report the matrix already wrote.
    fail_block="(none)"
    if [ -f "${DIR}/${ref}/${key}.md" ]; then
        block=$(awk '/^## Failure List/{f=1;next} f' "${DIR}/${ref}/${key}.md" \
                | sed -e '/^$/d' -e 's/^```$//')
        [ -n "$block" ] && [ "$block" != "(none)" ] && fail_block="$block"
    fi

    {
        echo "# ${title} Compatibility Test Report"
        echo
        echo "- **Generated:** $(date '+%Y-%m-%d %H:%M:%S %z')"
        echo "- **Reference combination:** \`${ref}\`"
        echo "- **Matrix run:** \`${DIR}\`"
        echo
        echo "> Auto-generated by \`scripts/gen_sdk_summary.sh\` from the SDK matrix"
        echo "> (\`scripts/test.sh sdk --matrix\`). Do not hand-edit: re-running the"
        echo "> matrix refreshes this file."
        echo
        echo "## Summary (${ref})"
        echo
        echo "| Metric | Count |"
        echo "|--------|-------|"
        echo "| Total tests | ${total} |"
        echo "| **Passed** | **${passed}** |"
        echo "| Failed | ${failed} |"
        echo "| Errors | ${errors} |"
        echo "| Skipped | ${skipped} |"
        echo
        echo "## Across combinations (passed/total)"
        echo
        echo "| Combination | Result |"
        echo "|-------------|--------|"
        for c in $(awk -F'|' -v k="$key" '$2==k {print $1}' "$RESULTS" | sort -u); do
            echo "| \`${c}\` | $(cell "$c" "$key") |"
        done
        echo
        echo "## Failure List (${ref})"
        echo
        echo '```'
        echo "$fail_block"
        echo '```'
    } > "$out"
    echo "wrote ${out}"
done
