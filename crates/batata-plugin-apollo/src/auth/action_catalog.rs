//! Machine-readable catalog of OpenAPI actions exposed to Apollo user tokens.
//!
//! Upstream reference: `UserTokenOpenApiController.ACTION_CATALOG` and the
//! `actions` field of `OpenUserTokenCurrentCapability`. An Agent can query its
//! identity, scope and the concrete actions its token may call instead of
//! guessing endpoints by trial and error.
//!
//! `actions_for` filters the catalog by the token scope only; the caller's
//! RBAC is enforced separately on each request, matching upstream's
//! `actionsFor` / `grantedOperationsFor` behaviour.

use crate::auth::token_scope::{TokenScope, operation as op};
use serde_json::{Value, json};

/// One machine-readable OpenAPI action.
#[derive(Debug, Clone, Copy)]
pub struct OpenApiAction {
    /// Stable action id used by Agents to refer to an operation.
    pub id: &'static str,
    /// HTTP method.
    pub method: &'static str,
    /// OpenAPI path.
    pub path: &'static str,
    /// Operations any of which grants this action.
    pub required_operations: &'static [&'static str],
    /// Resource family used as a scope hint.
    pub resource_scope: &'static str,
    /// Human-readable description.
    pub description: &'static str,
}

impl OpenApiAction {
    /// Builds a catalog entry.
    pub const fn new(
        id: &'static str,
        method: &'static str,
        path: &'static str,
        required_operations: &'static [&'static str],
        resource_scope: &'static str,
        description: &'static str,
    ) -> Self {
        Self {
            id,
            method,
            path,
            required_operations,
            resource_scope,
            description,
        }
    }
}

const fn a(
    id: &'static str,
    method: &'static str,
    path: &'static str,
    required_operations: &'static [&'static str],
    resource_scope: &'static str,
    description: &'static str,
) -> OpenApiAction {
    OpenApiAction::new(
        id,
        method,
        path,
        required_operations,
        resource_scope,
        description,
    )
}

